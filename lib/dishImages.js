// item: a menu_items row; base: the dish name without its size suffix.
// A photo set directly on the item in the database always wins.
export function imageForDish(item, base) {
  if (item && item.image_url) return item.image_url;
  if (base && DISH_IMAGES[base]) return DISH_IMAGES[base];
  if (item && CATEGORY_FALLBACK[item.category]) return CATEGORY_FALLBACK[item.category];
  return HERO_DISH_IMAGE;
}
